#!/usr/bin/env python3
"""Local-only signer setup for the Guardian L1 (L1-002). Test keys from the PUBLIC mnemonic only.

Writes two git-ignored files:
  Backend/.env.l1-local          CHAIN_MODE=l1 settings + one L1_KEY_<SEED_ID> per seed key / Council member
  infra/l1/seed.l1-local.json    Backend/seed/may_labs.json with the key and Council addresses replaced by
                                 the roster addresses (the addresses the L1 genesis enables), so that the
                                 deploy scripts and the backend agree on who is who

The mnemonic is the public "test ... junk" one (same as infra/l1/l1-local.sh and genesis roster.local.json):
every key it derives is known to the whole world and holds nothing of value. Never use it, or this script's
output, on a network that holds real funds. The script refuses to write a key whose address differs from the
roster, and prints addresses only.

Usage: python3 infra/l1/local_env.py [roster.json]   (default contracts/genesis/roster.local.json)
Needs `cast` (Foundry) to derive keys.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SEED = ROOT / "Backend" / "seed" / "may_labs.json"
ROSTER = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "contracts" / "genesis" / "roster.local.json"
OUT_ENV = Path(os.environ.get("L1_LOCAL_ENV_FILE") or ROOT / "Backend" / ".env.l1-local")
OUT_SEED = Path(os.environ.get("L1_LOCAL_SEED_FILE") or ROOT / "infra" / "l1" / "seed.l1-local.json")
STATE = ROOT / "infra" / "l1" / ".env.l1-local"  # RPC_URL=..., written by `l1-local.sh up`
MNEMONIC = os.environ.get("LOCAL_MNEMONIC", "test test test test test test test test test test test junk")

# roster id -> mnemonic index (the order used by genesis/roster.local.json)
INDEX = {
    "council_trang": 0,
    "council_lan": 1,
    "council_huy": 2,
    "key_agent_rebalance": 3,
    "key_agent_data": 4,
    "key_agent_intl_pay": 5,
    "key_svc_payment": 6,
    "key_minh": 7,
    "key_huy_1": 8,
    "key_huy_2": 9,
    "key_lan": 10,
    "backend_demo_signer": 11,
}


def cast(*args: str) -> str:
    exe = shutil.which("cast") or str(Path.home() / ".foundry" / "bin" / "cast")
    return subprocess.run([exe, *args], check=True, capture_output=True, text=True).stdout.strip()


def main() -> int:
    roster = json.loads(ROSTER.read_text())
    enabled = roster["enabled"]
    seed_text = SEED.read_text(encoding="utf-8")
    seed = json.loads(seed_text)

    env: list[str] = [
        "# Generated by infra/l1/local_env.py. PUBLIC test mnemonic keys, local network only. Git-ignored.",
        "CHAIN_MODE=l1",
        "DEMO_MODE=true",
        f"L1_CHAIN_ID={roster['chainId']}",
        "DEPLOYMENTS_FILE=deployments/local-l1.json",
        f"GUARDIAN_SEED_FILE={OUT_SEED}",
    ]
    if STATE.exists():
        rpc = dict(line.split("=", 1) for line in STATE.read_text().splitlines() if "=" in line).get("RPC_URL")
        if rpc:
            env += [f"L1_RPC_URL={rpc}", f"L1_WS_URL={rpc.replace('http', 'ws').removesuffix('/rpc')}/ws"]

    mapping: dict[str, str] = {}  # seed address (lower) -> roster address
    for entry in (*seed["keys"], *seed["council"]):
        sid = entry["seed_id"]
        want = enabled[sid]
        pk = cast("wallet", "private-key", "--mnemonic", MNEMONIC, "--mnemonic-index", str(INDEX[sid]))
        got = cast("wallet", "address", pk)
        if got.lower() != want.lower():
            sys.exit(f"{sid}: mnemonic index {INDEX[sid]} derives {got}, roster has {want}")
        mapping[entry["address"].lower()] = want
        env.append(f"L1_KEY_{sid.upper()}={pk}")
    # the seed lists each address exactly in these places; replace everywhere (policy_v2 args too)
    pattern = re.compile("|".join(re.escape(a) for a in mapping), re.IGNORECASE)
    OUT_SEED.write_text(
        pattern.sub(lambda m: mapping[m.group(0).lower()], seed_text), encoding="utf-8"
    )
    OUT_ENV.write_text("\n".join(env) + "\n", encoding="utf-8")
    OUT_ENV.chmod(0o600)

    print(f"wrote {OUT_ENV} ({len(mapping)} L1_KEY_* variables, values not shown)")
    print(f"wrote {OUT_SEED}")
    for old, new in mapping.items():
        print(f"  seed {old} -> {new}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
